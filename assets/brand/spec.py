"""Single source of truth for the Embed.Art identity.

Every committed SVG is emitted from here, so the mark's geometry cannot drift
between logo.svg, wordmark.svg, icon.svg and preview.svg: there is only one
copy of it, in MARK_* below.

Type outlines live in outlines.json, regenerated by make_outlines.py whenever
the copy or the type spec changes. This file never needs a font.
"""
